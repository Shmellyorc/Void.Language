#!/usr/bin/env python3
"""Regenerate the immutable date input from the vendored IANA source files."""
from pathlib import Path
import hashlib

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "third_party/tzdata"
FILES = ("africa", "antarctica", "asia", "australasia", "backward", "etcetera",
         "europe", "northamerica", "southamerica", "leapseconds")


def c_bytes(raw):
    return "".join(chr(c) if 32 <= c < 127 and c not in (34, 92)
                   else f"\\{c:03o}" for c in raw)


def generate():
    notices = b"\n\n".join((ROOT / path).read_bytes() for path in
                           ("third_party/date/NOTICE", "third_party/ryu/LICENSE-Boost",
                            "third_party/tzdata/LICENSE"))
    lines = ["// Generated by tools/embed_tzdata.py; do not edit.",
             "// IANA data license: third_party/tzdata/LICENSE (public domain).",
             "#pragma once", "#include <string>", "#include <string_view>",
             "namespace date { namespace detail {",
             f'constexpr char void_tzdb_version[] = "{(DATA / "version").read_text().strip()}";',
             'inline const char* volatile void_tzdb_notice_anchor = "' + c_bytes(notices) + '";',
             "inline std::string void_tzdb_file(std::string_view name) {"]
    for filename in FILES:
        raw = (DATA / filename).read_bytes()
        lines.append(f'// {filename}: SHA-256 {hashlib.sha256(raw).hexdigest()}')
        lines.append(f'if (name == "{filename}") {{')
        lines.append(f"std::string result; result.reserve({len(raw)});")
        # Separate append calls keep individual literals below the MSVC limit.
        for offset in range(0, len(raw), 4000):
            chunk = raw[offset:offset + 4000]
            # Octal escapes preserve UTF-8 comment bytes even on a non-UTF-8
            # Windows compiler host, without extending into the next digit.
            literal = c_bytes(chunk)
            lines.append('result.append("' + literal + '");')
        lines.extend(["return result;", "}"])
    lines.extend(["return {};", "}", "}}", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    target = ROOT / "third_party/date/src/void_embedded_tzdb.hpp"
    target.write_text(generate(), encoding="ascii", newline="\n")
