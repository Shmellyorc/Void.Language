"""Installed resource manifest checks only; no native build or platform execution."""
from contextlib import contextmanager
import importlib.util
import os
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('install_smoke', ROOT / 'tools/ci/install_smoke.py')
smoke = importlib.util.module_from_spec(spec)
spec.loader.exec_module(smoke)

LIBRARIES = {
    'Linux': ('libvoid_runtime.a', 'libvoid_native_fixture.a', 'libcurl.a', 'libpsl.a',
              'libnghttp2.a', 'libssl.a', 'libcrypto.a', 'libcares.a', 'libidn2.so',
              'libunistring.so', 'libz.a'),
    'Windows': ('void_runtime.lib', 'void_native_fixture.lib', 'libcurl.lib', 'psl.lib',
                'nghttp2.lib', 'cares.lib', 'zs.lib'),
    'Darwin': ('libvoid_runtime.a', 'libvoid_native_fixture.a', 'libcurl.a', 'libpsl.a',
               'libnghttp2.a', 'libssl.a', 'libcrypto.a', 'libcares.a', 'libz.a'),
}


@contextmanager
def installation(system):
    """Use the paths/argv forms generated by NativeBuild and HTTP dependencies."""
    with tempfile.TemporaryDirectory(prefix='void installed resources ') as directory:
        scratch = Path(directory).resolve()
        source = scratch / 'source'
        (source / 'stdlib').mkdir(parents=True)
        (source / 'stdlib/console.void').write_bytes(b'# fixture standard source\n')
        suffix = '.exe' if system == 'Windows' else ''
        linker = str(source / '.toolchains/llvm-23.1.4/bin/ld.lld') if system == 'Linux' else ''
        with patch.object(smoke, 'ROOT', source), patch.object(smoke, 'SYSTEM', system), \
                patch.object(smoke, 'SUFFIX', suffix), patch.dict(os.environ, {
                    'RUNNER_TEMP': str(scratch), 'INSTALL_QUALIFICATION_NAME': 'qualification',
                    'VOID_LINKER': linker}):
            q = smoke.Qualification()
            q.bin.mkdir(parents=True)
            library_dir = q.prefix / 'lib/void'
            library_dir.mkdir(parents=True)
            installed_stdlib = q.prefix / 'share/void/stdlib'
            installed_stdlib.mkdir(parents=True)
            (installed_stdlib / 'console.void').write_bytes((source / 'stdlib/console.void').read_bytes())
            for executable in (q.voidc, q.voidls):
                executable.write_bytes(b'fixture executable; never executed')
            for name in LIBRARIES[system]:
                (library_dir / name).write_bytes(('fixture resource ' + name).encode('utf-8'))
            # Runtime archives use ../ paths; HTTP resources use the manifest token.
            links = ['../lib/void/' + name if i < 2 else '@VOID_NATIVE_DIR@/../lib/void/' + name
                     for i, name in enumerate(LIBRARIES[system])]
            if system == 'Linux':
                flags = ['-Xlinker', '-rpath', '-Xlinker', '@VOID_NATIVE_DIR@/../lib/void',
                         '-pthread', '-Xlinker', '--exclude-libs', '-Xlinker',
                         'libcurl.a:libssl.a:libcrypto.a:libcares.a:libnghttp2.a:libpsl.a:libz.a']
            elif system == 'Windows':
                flags = ['-fms-runtime-lib=static', '-llegacy_stdio_definitions', '-lbcrypt',
                         '-lshell32', '-lole32', '-luuid', '-lws2_32', '-lcrypt32', '-lsecur32',
                         '-lnormaliz', '-liphlpapi', '-ladvapi32', '-lbcrypt']
            else:
                sdk = str(scratch / 'Xcode SDKs/MacOSX.sdk')
                flags = ['-pthread', '-stdlib=libc++', '-nostdinc++', '-isystem', sdk + '/usr/include/c++/v1',
                         '-framework', 'Foundation', '-lobjc', '-isysroot', sdk, '-arch', 'arm64',
                         '-mmacosx-version-min=14.0', '-framework', 'Security', '-framework',
                         'CoreFoundation', '-framework', 'CoreServices', '-licucore', '-liconv']
            (q.bin / 'void-native.txt').write_text('\n'.join([
                'VOID native 23.1.4 v2', str(q.sdk / 'bin' / ('clang' + suffix)), linker,
                *links, *flags]) + '\n', encoding='utf-8')
            inventory = ['VOID native resources 1'] + [
                smoke.digest(library_dir / name) + '\t@VOID_NATIVE_DIR@/../lib/void/' + name
                for name in LIBRARIES[system]]
            (q.bin / 'void-native-resources.txt').write_text('\n'.join(inventory) + '\n', encoding='utf-8')
            yield q


def remove_lines(path, predicate):
    lines = path.read_text(encoding='utf-8').splitlines()
    path.write_text('\n'.join(line for line in lines if not predicate(line)) + '\n', encoding='utf-8')


class LayoutTests(unittest.TestCase):
    def test_linux_layout_accepts_shared_resources_and_linker_operands(self):
        with installation('Linux') as q:
            q.layout()

    def test_windows_layout_accepts_lib_resources_and_system_libraries(self):
        with installation('Windows') as q:
            q.layout()

    def test_macos_layout_accepts_archives_frameworks_and_sdk_operands(self):
        with installation('Darwin') as q:
            q.layout()

    def test_linux_exclusion_list_is_not_a_file_resource(self):
        with installation('Linux') as q:
            # Isolate the .a-looking linker operand from the shared-library defect.
            for name in ('void-native.txt', 'void-native-resources.txt'):
                remove_lines(q.bin / name, lambda line: line.endswith(('/libidn2.so', '/libunistring.so')))
            q.layout()

    def test_linux_shared_aliases_and_versioned_files_are_resources(self):
        for versioned_entries in (False, True):
            with self.subTest(versioned_entries=versioned_entries), installation('Linux') as q:
                for name, version in (('libidn2.so', '.0.4.0'), ('libunistring.so', '.5.2.1')):
                    library = q.prefix / 'lib/void' / name
                    library.rename(library.with_name(name + version))
                    if versioned_entries:
                        for manifest in ('void-native.txt', 'void-native-resources.txt'):
                            path = q.bin / manifest
                            path.write_text(path.read_text(encoding='utf-8').replace('/' + name + '\n', '/' + name + version + '\n'), encoding='utf-8')
                    else:
                        library.symlink_to(name + version)
                q.layout()

    def test_hashed_resource_omitted_from_link_manifest_is_rejected(self):
        for system, name in (('Linux', 'libidn2.so'), ('Linux', 'libunistring.so'),
                             ('Windows', 'nghttp2.lib'), ('Darwin', 'libssl.a')):
            with self.subTest(system=system, name=name), installation(system) as q:
                remove_lines(q.bin / 'void-native.txt', lambda line: line.endswith('/' + name))
                with self.assertRaisesRegex(RuntimeError, 'hashed resource inventory differ'):
                    q.layout()

    def test_unhashed_file_argument_is_rejected_before_and_after_flags(self):
        for system, name in (('Linux', 'unhashed.so'), ('Windows', 'unhashed.lib'), ('Darwin', 'unhashed.a')):
            for after_flags in (False, True):
                with self.subTest(system=system, after_flags=after_flags), installation(system) as q:
                    (q.prefix / 'lib/void' / name).write_bytes(b'unhashed link input')
                    manifest = q.bin / 'void-native.txt'
                    lines = manifest.read_text(encoding='utf-8').splitlines()
                    lines.insert(len(lines) if after_flags else 3, '@VOID_NATIVE_DIR@/../lib/void/' + name)
                    manifest.write_text('\n'.join(lines) + '\n', encoding='utf-8')
                    with self.assertRaisesRegex(RuntimeError, 'hashed resource inventory differ'):
                        q.layout()

    def test_linked_shared_library_without_inventory_entry_is_rejected(self):
        for name in ('libidn2.so', 'libunistring.so'):
            with self.subTest(name=name), installation('Linux') as q:
                remove_lines(q.bin / 'void-native-resources.txt', lambda line: line.endswith('/' + name))
                with self.assertRaisesRegex(RuntimeError, 'hashed resource inventory differ'):
                    q.layout()

    def test_resource_corruption_is_rejected_on_all_platform_representations(self):
        for system, name in (('Linux', 'libidn2.so'), ('Windows', 'nghttp2.lib'), ('Darwin', 'libssl.a')):
            with self.subTest(system=system), installation(system) as q:
                (q.prefix / 'lib/void' / name).write_bytes(b'corrupt')
                with self.assertRaisesRegex(RuntimeError, 'Native resource hash mismatch'):
                    q.layout()

    def test_missing_resource_is_rejected_on_all_platform_representations(self):
        for system, name in (('Linux', 'libunistring.so'), ('Windows', 'nghttp2.lib'), ('Darwin', 'libssl.a')):
            with self.subTest(system=system), installation(system) as q:
                (q.prefix / 'lib/void' / name).unlink()
                with self.assertRaisesRegex(RuntimeError, 'Resource escapes prefix or is missing'):
                    q.layout()

    def test_inventory_cannot_escape_private_prefix(self):
        with installation('Linux') as q:
            outside = q.work / 'outside.so'
            outside.write_bytes(b'outside prefix')
            with (q.bin / 'void-native-resources.txt').open('a', encoding='utf-8') as stream:
                stream.write(smoke.digest(outside) + '\t@VOID_NATIVE_DIR@/../lib/void/../../../outside.so\n')
            with self.assertRaisesRegex(RuntimeError, 'Resource escapes prefix or is missing'):
                q.layout()

    def test_shared_library_symlink_cannot_escape_private_prefix(self):
        with installation('Linux') as q:
            library = q.prefix / 'lib/void/libidn2.so'
            outside = q.work / 'outside.so'
            library.rename(outside)
            library.symlink_to(outside)
            with self.assertRaisesRegex(RuntimeError, 'Resource escapes prefix or is missing'):
                q.layout()

    def test_native_manifest_and_static_crt_checks_are_preserved(self):
        for system in LIBRARIES:
            for index, replacement, diagnostic in (
                    (0, 'VOID native invalid', 'Invalid installed native manifest version'),
                    (1, '/other-sdk/clang', 'Native driver differs from pinned SDK'),
                    (2, '/other-sdk/linker', 'Wrong native linker override')):
                with self.subTest(system=system, index=index), installation(system) as q:
                    manifest = q.bin / 'void-native.txt'
                    lines = manifest.read_text(encoding='utf-8').splitlines()
                    lines[index] = replacement
                    manifest.write_text('\n'.join(lines) + '\n', encoding='utf-8')
                    with self.assertRaisesRegex(RuntimeError, diagnostic):
                        q.layout()
        with installation('Windows') as q:
            remove_lines(q.bin / 'void-native.txt', lambda line: line == '-fms-runtime-lib=static')
            with self.assertRaisesRegex(RuntimeError, 'Native Windows static CRT contract missing'):
                q.layout()

    def test_inventory_version_and_install_relative_paths_are_preserved(self):
        for malformed, diagnostic in (('VOID native resources invalid\n', 'Invalid resource inventory version'),
                                      ('VOID native resources 1\n' + '0' * 64 + '\t/ambient/libidn2.so\n',
                                       'Resource is not installation relative')):
            with self.subTest(diagnostic=diagnostic), installation('Linux') as q:
                (q.bin / 'void-native-resources.txt').write_text(malformed, encoding='utf-8')
                with self.assertRaisesRegex(RuntimeError, diagnostic):
                    q.layout()

    def test_dangling_linker_option_is_rejected(self):
        with installation('Darwin') as q:
            with (q.bin / 'void-native.txt').open('a', encoding='utf-8') as stream:
                stream.write('-framework\n')
            with self.assertRaisesRegex(RuntimeError, 'Native linker option lacks an operand'):
                q.layout()


if __name__ == '__main__':
    unittest.main(verbosity=2)
