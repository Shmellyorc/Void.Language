"""Measure the same host with default GC policy; preserve the GC-stress samples.

Only a test-host source overlay changes: Runtime allocation budget 1 -> 256,
matching normal JIT creation and native bootstrap in the production sources.
Existing profile compile/link recipes and all production libraries are reused.
The exact overlay, commands and hashes remain in the shared evidence store.
"""
from pathlib import Path
import json, re, shlex, sys
import support as h

build = Path(sys.argv[1]).resolve()
source = (h.ROOT / 'tests/log/host.cpp').read_text()
assert source.count('std::make_shared<vd::Runtime>(1') == 4
source = source.replace('std::make_shared<vd::Runtime>(1', 'std::make_shared<vd::Runtime>(256')
source = source.replace('#include "../managed/probe.hpp"',
                        '#include "' + str(h.ROOT / 'tests/managed/probe.hpp') + '"')
overlay = h.EVIDENCE / 'benchmark-default-host.cpp'
overlay.write_text('// Test-only overlay generated by tests/log/benchmarks_default.py.\n' + source)
previous = h.EVIDENCE / 'benchmarks.json'
if previous.exists() and not (h.EVIDENCE / 'benchmarks-gc-stress.json').exists():
    (h.EVIDENCE / 'benchmarks-gc-stress.json').write_bytes(previous.read_bytes())
executables = []
for target in ('void_log_host', 'void_log_probe_normal', 'void_log_probe_optimized'):
    files = build / 'CMakeFiles' / (target + '.dir')
    definitions = dict(re.findall(r'^(CXX_\w+) = (.*)$', (files / 'flags.make').read_text(), re.M))
    link = shlex.split((files / 'link.txt').read_text())
    obj = build / (target + '-benchmark-default.o')
    exe = build / (target + '-benchmark-default')
    args = [link[0]]
    for name in ('CXX_DEFINES', 'CXX_INCLUDES', 'CXX_FLAGS'):
        args.extend(shlex.split(definitions[name]))
    h.run([*args, '-c', overlay, '-o', obj], cwd=build, sources=[overlay], small=True)
    expected_object = f'CMakeFiles/{target}.dir/tests/log/host.cpp.o'
    assert link.count(expected_object) == 1
    link[link.index(expected_object)] = str(obj)
    link[link.index('-o') + 1] = str(exe)
    h.run(link, cwd=build, sources=[overlay], small=True)
    executables.append(exe)
result = h.run([sys.executable, h.ROOT / 'tests/log/benchmarks.py', *executables],
               sources=[overlay], timeout=1800)
print(result.stdout.decode(), end='')
rows = json.loads(previous.read_text())
selected = [row for row in rows if row['executable'] in set(map(str, executables))]
assert len(selected) == 216
for row in selected:
    row.update(gc_allocation_budget=256, host_overlay_sha256=h.crash.digest(overlay))
previous.write_text(json.dumps(selected, indent=2) + '\n')
print('Default Runtime GC policy: 216 samples; the separate original stress samples are retained')
