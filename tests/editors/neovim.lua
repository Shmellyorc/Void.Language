local root=assert(vim.env.VOID_STAGE7_FIXTURE)
local repo=assert(vim.env.VOID_REPO)
local output=assert(vim.env.VOID_STAGE7_OUTPUT)
local function check(ok,msg)if not ok then error(msg)end end
local function wait(fn)check(vim.wait(10000,fn,10),'timeout: '..debug.traceback())end
local function main()
  vim.opt.runtimepath:prepend(repo..'/editors/neovim')
  vim.opt.runtimepath:prepend(repo..'/editors/vim')
  vim.cmd('filetype plugin indent on')
  local adapter=require('void');adapter.setup({server=vim.env.VOIDLS_PATH,entry=root..'/main.void'})
  vim.cmd.edit(vim.fn.fnameescape(root..'/main.void'))
  wait(function()return #vim.lsp.get_clients({bufnr=0,name='voidls'})==1 and vim.lsp.get_clients({bufnr=0,name='voidls'})[1].initialized end)
  local c=vim.lsp.get_clients({bufnr=0,name='voidls'})[1]
  local buf=vim.api.nvim_get_current_buf()
  local uri=vim.uri_from_fname(root..'/main.void')
  local function request(method,params)
    local result=c:request_sync(method,params,10000,vim.api.nvim_get_current_buf())
    check(result and not result.err,'request failed: '..method..' '..vim.inspect(result));return result.result
  end
  local function point(line,char)return {textDocument={uri=uri},position={line=line,character=char}}end
  check(c.server_capabilities.renameProvider,'guarded adapter rename unavailable')
  local def=request('textDocument/definition',point(2,18));check(vim.uri_to_fname(def.uri)==root..'/worker.void','definition '..vim.inspect(def)..' '..vim.inspect(vim.diagnostic.get()))
  check(request('textDocument/hover',point(2,18)).contents.value:find('calculate',1,true),'hover')
  check(vim.bo.expandtab and vim.bo.shiftwidth==4,'filetype indentation')
  local symbols=request('workspace/symbol',{query='calc'});check(#symbols==1,'workspace symbol')
  vim.api.nvim_buf_set_lines(buf,2,3,false,{'    return worker.'})
  local items=request('textDocument/completion',point(2,18));check(#items==1 and items[1].label=='calculate','incomplete member completion')
  vim.lsp.util.apply_text_edits({items[1].textEdit},buf,'utf-16')
  check(vim.api.nvim_buf_get_lines(buf,2,3,false)[1]=='    return worker.calculate','completion selection')
  vim.api.nvim_buf_set_lines(buf,2,3,false,{'    return worker.calculate('})
  local sig=request('textDocument/signatureHelp',point(2,28));check(sig.activeParameter==0 and sig.signatures[1].label:find('x: i32',1,true),'signature')
  vim.api.nvim_buf_set_lines(buf,2,3,false,{'    return worker.calculate(x)'})
  wait(function()return #vim.diagnostic.get(buf)==0 end)
  local worker=vim.fn.bufadd(root..'/worker.void');vim.fn.bufload(worker)
  vim.api.nvim_set_current_buf(worker)
  wait(function()return #vim.lsp.get_clients({bufnr=worker})==1 end)
  vim.api.nvim_buf_set_lines(worker,1,2,false,{'    return missing'})
  wait(function()for _,d in ipairs(vim.diagnostic.get(worker))do if d.code=='VOID2002' then return true end end end)
  local stale=request('textDocument/definition',point(2,18));check(stale==vim.NIL or stale==nil,'stale definition '..vim.inspect(stale))
  vim.api.nvim_buf_set_lines(worker,1,2,false,{'    return x + 1'})
  wait(function()return #vim.diagnostic.get(worker)==0 end)
  local rename=request('textDocument/rename',{textDocument={uri=vim.uri_from_fname(root..'/worker.void')},position={line=0,character=7},newName='compute'})
  check(adapter.versioned_edit(rename),'rename application')
  check(vim.api.nvim_buf_get_lines(buf,2,3,false)[1]=='    return worker.compute(x)','cross-file rename')
  check(not adapter.versioned_edit({documentChanges={{textDocument={uri=vim.uri_from_bufnr(worker),version=vim.NIL},edits={}}}}),'unversioned dirty target accepted')
  local before=vim.api.nvim_buf_get_lines(worker,0,-1,false)
  check(not adapter.versioned_edit({documentChanges={{textDocument={uri=vim.uri_from_bufnr(worker),version=-1},edits={}}}}),'stale edit accepted')
  check(vim.deep_equal(before,vim.api.nvim_buf_get_lines(worker,0,-1,false)),'stale edit mutated source')
  vim.api.nvim_buf_set_lines(worker,1,2,false,{'  return x + 1'})
  adapter.format()
  wait(function()return vim.api.nvim_buf_get_lines(worker,1,2,false)[1]=='    return x + 1'end)
  check(#request('textDocument/formatting',{textDocument={uri=vim.uri_from_bufnr(worker)},options={tabSize=4,insertSpaces=true}})==0,'format idempotence')
  vim.api.nvim_buf_set_lines(worker,1,2,false,{'  return x + 1'})
  adapter.format()
  vim.api.nvim_buf_set_lines(worker,1,2,false,{'    return x + 99'})
  request('workspace/symbol',{query='compute'})
  check(vim.api.nvim_buf_get_lines(worker,1,2,false)[1]=='    return x + 99','stale formatting overwrote a newer edit')
  adapter.refresh()
  vim.cmd('VoidRestart')
  wait(function()local all=vim.lsp.get_clients({bufnr=worker,name='voidls'});return #all==1 and all[1].id~=c.id and all[1].initialized end)
  wait(function()return c:is_stopped()end)
  local replacement=vim.lsp.get_clients({bufnr=worker,name='voidls'})[1]
  replacement:stop();wait(function()return replacement:is_stopped()end)
  vim.fn.writefile({vim.json.encode({editor=vim.version(),passed={'shipped adapter','completion selection','incomplete call signature','hover','symbols','navigation','dirty repair','cross-file guarded rename','stale edit rejection','stale formatting rejection','formatting','refresh','restart','stop'}})},output)
end
local ok,err=pcall(main)
if not ok then vim.fn.writefile({tostring(err)},output..'.error');vim.cmd('cquit 1')else vim.cmd('qa!')end
