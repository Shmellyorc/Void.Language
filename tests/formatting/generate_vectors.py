"""Independent exact Decimal oracle; regenerate the checked-in numeric vectors."""
from decimal import Decimal, localcontext, ROUND_HALF_EVEN
from pathlib import Path
import json
import math
import random
import struct

rng = random.Random(0x564F4944)
lines = ["// Generated by generate_vectors.py using Decimal.from_float / ROUND_HALF_EVEN."]
for width in (32, 64):
    samples = [0, 1, (1 << width) - 1, 1 << (width - 1)]
    samples += [rng.getrandbits(width) for _ in range(160)]
    for bits in samples:
        value = struct.unpack(">f" if width == 32 else ">d", bits.to_bytes(width // 8, "big"))[0]
        if not math.isfinite(value):
            continue
        for precision, percent in ((0, False), (2, False), (7, False), (2, True)):
            with localcontext() as ctx:
                ctx.prec = 2000
                exact = Decimal.from_float(value)
                if percent:
                    exact *= 100
                rounded = exact.quantize(Decimal(1).scaleb(-precision), rounding=ROUND_HALF_EVEN)
                expected = format(rounded, "f") + ("%" if percent else "")
            spec = ("P" if percent else "F") + str(precision)
            lines.append(f'check({{NumberKind::f{width}, UINT64_C({bits})}}, {json.dumps(spec)}, {json.dumps(expected)});')
Path(__file__).with_name("vectors.inc").write_text("\n".join(lines) + "\n")
